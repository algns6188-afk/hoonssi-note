export const DICTS: Record<Lang, Dict> = { ko, zh, ru, en }

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('lang') as Lang | null
    if (saved && saved in DICTS) return saved
  } catch {
    // 저장소를 못 쓰는 환경
  }
  const nav = (navigator.language || 'ko').slice(0, 2)
  return (['zh', 'ru', 'en'] as Lang[]).includes(nav as Lang) ? (nav as Lang) : 'ko'
}

export const LangContext = createContext<{ lang: Lang; t: Dict; setLang(l: Lang): void }>({
  lang: 'ko',
  t: ko,
  setLang: () => {}
})
export const useI18n = (): { lang: Lang; t: Dict; setLang(l: Lang): void } => useContext(LangContext)

/** 날짜를 각 언어에 맞게: 11/15 (토) */
export function dayLabel(iso: string, t: Dict): string {
  const d = new Date(new Date(iso).getTime() + 9 * 3600_000)
  const wd = t.weekdays.split(',')[d.getUTCDay()]
  return `${d.getUTCMonth() + 1}/${d.getUTCDate()} (${wd})`
}
